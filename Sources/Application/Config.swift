// ゲームの調整用の数値。ここを変えるだけで遊び心地が大きく変わる。
//
// 単位について:
//   GBAには小数を計算する回路がないので、動くものの位置と速さは
//   「1/256 ピクセル」単位の整数で持っている (256 で 1ピクセル)。
//   大きさや、動かないものの位置はピクセル単位。

enum Config {
    // MARK: - 鳥

    /// 鳥の左端の位置 (ピクセル)。鳥は横には動かない。
    static let birdX = 56
    /// ゲーム開始前の鳥の高さ (ピクセル)
    static let birdStartY = 64
    /// 重力: 毎フレーム、落ちる速さに足される量 (1/256 ピクセル)
    static let gravity = 28
    /// 羽ばたいた直後の速さ (1/256 ピクセル/フレーム)。マイナスが上向き。
    static let flapVelocity = -540
    /// 落ちる速さの上限 (1/256 ピクセル/フレーム)
    static let maxFallSpeed = 768

    // MARK: - 土管

    /// 土管と地面が左へ流れる速さ (1/256 ピクセル/フレーム)。320 で 1.25ピクセル。
    static let scrollSpeed = 320
    /// 上下の土管の隙間 (ピクセル)
    static let pipeGap = 52
    /// 土管から次の土管までの間隔 (ピクセル)
    static let pipeSpacing = 104
    /// 隙間を画面の上端や地面にどこまで近づけてよいか (ピクセル)
    static let pipeMargin = 16

    // MARK: - 画面

    /// 地面の上端の位置 (ピクセル、8の倍数)。画面の高さは 160。
    static let groundY = 136
}
