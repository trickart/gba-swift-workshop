func fail(_ message: String) -> Never {
    var line = "gbafix: \(message)\n"
    line.withUTF8 { _ = write(2, $0.baseAddress, $0.count) }
    exit(1)
}

/// ファイル全体を読み込む
func readFile(_ path: String) -> [UInt8] {
    guard let file = fopen(path, "rb") else { fail("cannot open \(path)") }
    defer { fclose(file) }
    fseek(file, 0, SEEK_END)
    let size = ftell(file)
    guard size >= 0 else { fail("cannot determine size of \(path)") }
    rewind(file)
    var bytes = [UInt8](repeating: 0, count: size)
    guard fread(&bytes, 1, size, file) == size else { fail("cannot read \(path)") }
    return bytes
}

/// ファイル全体を書き戻す
func writeFile(_ path: String, _ bytes: [UInt8]) {
    guard let file = fopen(path, "wb") else { fail("cannot open \(path) for writing") }
    defer { fclose(file) }
    guard fwrite(bytes, 1, bytes.count, file) == bytes.count else { fail("cannot write \(path)") }
}

let arguments = CommandLine.arguments
guard arguments.count == 2 else {
    fail("usage: swift tools/gbafix.swift <image>")
}
let path = arguments[1]

var image = readFile(path)
guard image.count >= headerEnd else {
    fail("\(path) is smaller than a GBA header (\(headerEnd) bytes)")
}

image.replaceSubrange(logoOffset..<(logoOffset + logo.count), with: logo)
image[fixedValueOffset] = 0x96

var sum: UInt8 = 0
for offset in 0xA0..<checksumOffset {
    sum &+= image[offset]
}
image[checksumOffset] = 0 &- (0x19 &+ sum)

writeFile(path, image)
print("gbafix: fixed header of \(path)")
